-- ============================================================
-- FIRMEZA DATABASE-FIRST SCHEMA DEFINITION
-- Base de datos: firmeza_db
-- Motor: PostgreSQL 18.x
-- ============================================================

-- 1. TABLA: productos
CREATE TABLE IF NOT EXISTS productos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(150) NOT NULL,
    precio numeric(12,2) NOT NULL,
    stock integer NOT NULL DEFAULT 0,
    CONSTRAINT chk_productos_precio CHECK (precio >= 0),
    CONSTRAINT chk_productos_stock CHECK (stock >= 0)
);

CREATE INDEX IF NOT EXISTS idx_productos_nombre ON productos (nombre);

-- 2. TABLA: clientes
CREATE TABLE IF NOT EXISTS clientes (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento varchar(20) NOT NULL UNIQUE,
    nombre varchar(150) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_clientes_nombre ON clientes (nombre);

-- 3. TABLA: ventas
CREATE TABLE IF NOT EXISTS ventas (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_venta varchar(50) NOT NULL UNIQUE,
    fecha timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cliente_id integer NOT NULL,
    subtotal numeric(12,2) NOT NULL,
    iva numeric(12,2) NOT NULL,
    total numeric(12,2) NOT NULL,
    CONSTRAINT fk_ventas_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id) ON DELETE RESTRICT,
    CONSTRAINT chk_ventas_subtotal CHECK (subtotal >= 0),
    CONSTRAINT chk_ventas_iva CHECK (iva >= 0),
    CONSTRAINT chk_ventas_total CHECK (total >= 0)
);

CREATE INDEX IF NOT EXISTS idx_ventas_cliente_id ON ventas (cliente_id);
CREATE INDEX IF NOT EXISTS idx_ventas_fecha ON ventas (fecha);

-- 4. TABLA: detalles_venta
CREATE TABLE IF NOT EXISTS detalles_venta (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id integer NOT NULL,
    producto_id integer NOT NULL,
    cantidad integer NOT NULL,
    precio_unitario numeric(12,2) NOT NULL,
    subtotal numeric(12,2) NOT NULL,
    CONSTRAINT fk_detalles_venta_venta FOREIGN KEY (venta_id) REFERENCES ventas (id) ON DELETE CASCADE,
    CONSTRAINT fk_detalles_venta_producto FOREIGN KEY (producto_id) REFERENCES productos (id) ON DELETE RESTRICT,
    CONSTRAINT chk_detalles_venta_cantidad CHECK (cantidad > 0),
    CONSTRAINT chk_detalles_venta_precio_unitario CHECK (precio_unitario >= 0),
    CONSTRAINT chk_detalles_venta_subtotal CHECK (subtotal >= 0)
);

CREATE INDEX IF NOT EXISTS idx_detalles_venta_venta_id ON detalles_venta (venta_id);
CREATE INDEX IF NOT EXISTS idx_detalles_venta_producto_id ON detalles_venta (producto_id);
